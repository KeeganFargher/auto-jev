import * as THREE from "three";
import { part } from "./world-models.js";
const box=new THREE.BoxGeometry(1,1,1),cone=new THREE.ConeGeometry(1,1,4),cylinder=new THREE.CylinderGeometry(1,1,1,8);

/** Builds a tiered industrial silhouette inside its authoritative three-by-three footprint. */
export function createIndustryModel(building,definition,color){
  const group=new THREE.Group();
  part(group,box,"#958b71",[0,.08,0],[2.8,.16,2.8]);
  const tier=Math.max(1,building.tier);
  const water=definition.category==="Water",food=definition.category==="Food",frontier=definition.category==="Frontier";
  const wall=tier===1?"#b58a61":tier===2?"#b69580":"#91a0a0";
  if(building.kind==="farm"){
    part(group,box,"#785239",[0,.19,0],[2.6,.12,2.6]);
    for(let row=-1;row<=1;row++)for(let col=-1;col<=1;col++)part(group,cone,tier===3?"#a4d399":"#d4bd68",[row*.7,.48,col*.7],[.25,.7,.25]);
    if(tier>=2)for(const x of [-1.2,1.2])part(group,cylinder,"#6897a2",[x,.3,0],[.06,2.5,.06]).rotation.x=Math.PI/2;
  }else if(water){
    part(group,cylinder,"#658f9a",[0,.65,0],[.8,1.1,.8]);
    part(group,cylinder,"#9fd8db",[0,1.22,0],[.7,.04,.7]);
    const rotor=part(group,box,"#dec18b",[0,1.65,0],[2,.12,.15]);rotor.name="industry-rotor";
    part(group,box,"#527f85",[.8,.3,.7],[1.3,.2,.2]);
  }else{
    const height=frontier?1.4+tier*.4:.65+tier*.35;
    part(group,box,wall,[0,height/2+.15,0],[1.9,height,1.8]);
    part(group,cone,food?"#bd985c":frontier?color:"#7c8470",[0,height+.5,0],[1.5,.75,1.4]).rotation.y=Math.PI/4;
    part(group,box,"#423f37",[0,.5,1],[.5,.8,.06]);
    if(["Industry","Materials"].includes(definition.category)){
      part(group,box,"#746e68",[-.7,1.55,-.5],[.35,2.8,.35]);
      const wheel=part(group,cylinder,"#b8bdac",[1.15,.7,0],[.55,.15,.55]);wheel.rotation.z=Math.PI/2;wheel.name="industry-rotor";
    }
    if(building.kind==="mill"){
      const sails=part(group,box,"#ece0bc",[0,height+.6,1.2],[2.5,.18,.1]);sails.name="industry-rotor";
      part(group,box,"#ece0bc",[0,height+.6,1.2],[.18,2.5,.1]);
    }
    if(["clinic","school"].includes(building.kind))part(group,box,building.kind==="clinic"?"#cf7569":"#e0c376",[.5,1.2,1.01],[.4,.4,.07]);
    if(["iron_mine","coal_mine","quarry","clay_pit"].includes(building.kind))part(group,box,"#343f3c",[0,.21,1.1],[1.8,.04,.7]);
  }
  part(group,box,color,[1.12,1.35,.85],[.12,1.7,.12]);
  part(group,box,color,[1.35,2.02,.85],[.55,.35,.05]);
  for(let i=0;i<tier;i++)part(group,box,"#efd58b",[-.45+i*.35,.23,1.4],[.2,.15,.08]);
  return group;
}

/** Renders exactly the walkable island, waterways and crossings generated by the server. */
export function createTerrain(width,height,terrain){
  const vertices=[],colors=[];
  const palette={g:"#b3c788",f:"#82a772",s:"#d9c59a",w:"#75b9c5",m:"#929e92",r:"#b69569"};
  for(let y=0;y<height;y++)for(let x=0;x<width;x++){
    const tile=terrain.tiles[y*width+x];
    const h=tile==="w"?-.12:0;
    const tint=new THREE.Color(palette[tile]).multiplyScalar(.95+((x*17+y*13)%7)*.015);
    for(const [dx,dy]of [[0,0],[0,1],[1,0],[1,0],[0,1],[1,1]]){
      vertices.push(x+dx-width/2,h,y+dy-height/2);colors.push(tint.r,tint.g,tint.b);
    }
  }
  const geometry=new THREE.BufferGeometry();geometry.setAttribute("position",new THREE.Float32BufferAttribute(vertices,3));geometry.setAttribute("color",new THREE.Float32BufferAttribute(colors,3));geometry.computeVertexNormals();
  const group=new THREE.Group();const ground=new THREE.Mesh(geometry,new THREE.MeshStandardMaterial({vertexColors:true,roughness:1,flatShading:true}));ground.receiveShadow=true;group.add(ground);
  for(let y=4;y<height-4;y+=3)for(let x=4;x<width-4;x+=3)if(terrain.tiles[y*width+x]==="m")part(group,cone,"#929989",[x-width/2,1.4,y-height/2],[2.4,2.8+(x%3),2.4]);
  return group;
}
